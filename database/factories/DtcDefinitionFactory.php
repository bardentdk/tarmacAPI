<?php

namespace Database\Factories;

use App\Enums\DtcUrgency;
use App\Models\DtcDefinition;
use Illuminate\Database\Eloquent\Factories\Factory;

/**
 * @extends Factory<DtcDefinition>
 */
class DtcDefinitionFactory extends Factory
{
    /**
     * Define the model's default state.
     *
     * @return array<string, mixed>
     */
    public function definition(): array
    {
        return [
            'code' => 'P'.fake()->unique()->numerify('2###'),
            'make' => '',
            'engine' => '',
            'title' => fake()->sentence(4),
            'system' => 'Gestion moteur',
            'explanation' => fake()->paragraph(),
            'urgency' => fake()->randomElement(DtcUrgency::values()),
            'can_drive_note' => fake()->sentence(),
            'source' => 'kb',
        ];
    }

    /**
     * A definition specific to a make (and optionally an engine).
     */
    public function forVehicle(string $make, string $engine = ''): static
    {
        return $this->state(fn (array $attributes): array => [
            'make' => strtolower($make),
            'engine' => strtolower($engine),
        ]);
    }

    /**
     * A definition generated by AI.
     */
    public function ai(): static
    {
        return $this->state(fn (array $attributes): array => ['source' => 'ai']);
    }
}
